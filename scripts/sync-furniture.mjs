// Copies the Kenney furniture sprites used in lib/home-data.ts (all four views, so items can be
// rotated) into public/qn/furniture and writes lib/furniture-sizes.ts: each sprite's width, height
// and the x of its lowest pixel (the front corner of the item on the floor, used to work out how
// much floor it covers). Run after adding or changing sprites: npm run furniture
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { inflateSync } from "node:zlib";

const KIT = "components/kenney_furniture-kit/Isometric";
const OUT = "public/qn/furniture";
const DIRS = ["SE", "SW", "NW", "NE"];

/** Decode a non-interlaced 8-bit PNG (palette, RGB or RGBA) into width, height and an alpha getter. */
function decodeAlpha(buf) {
  let pos = 8;
  let width = 0, height = 0, type = 0, depth = 0, trns = null;
  const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos);
    const kind = buf.toString("ascii", pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    if (kind === "IHDR") {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      depth = data[8];
      type = data[9];
      if (data[12] !== 0) throw new Error("interlaced PNGs are not supported");
    } else if (kind === "tRNS") trns = data;
    else if (kind === "IDAT") idat.push(data);
    pos += 12 + len;
  }
  if (depth !== 8) throw new Error(`unsupported bit depth ${depth}`);
  const bpp = { 0: 1, 2: 3, 3: 1, 4: 2, 6: 4 }[type];
  const raw = inflateSync(Buffer.concat(idat));
  const stride = width * bpp;
  const px = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let i = 0; i < stride; i++) {
      const a = i >= bpp ? px[y * stride + i - bpp] : 0;
      const b = y > 0 ? px[(y - 1) * stride + i] : 0;
      const c = i >= bpp && y > 0 ? px[(y - 1) * stride + i - bpp] : 0;
      const p = a + b - c;
      const pred = [0, a, b, Math.floor((a + b) / 2), Math.abs(p - a) <= Math.abs(p - b) && Math.abs(p - a) <= Math.abs(p - c) ? a : Math.abs(p - b) <= Math.abs(p - c) ? b : c][filter];
      px[y * stride + i] = (line[i] + pred) & 255;
    }
  }
  const alpha = (x, y) => {
    const o = y * stride + x * bpp;
    if (type === 6) return px[o + 3];
    if (type === 4) return px[o + 1];
    if (type === 3) return trns && px[o] < trns.length ? trns[px[o]] : 255;
    return 255;
  };
  return { width, height, alpha };
}

/** x of the item's front corner: the middle of the lowest row of solid pixels. */
function frontX({ width, height, alpha }) {
  for (let y = height - 1; y >= 0; y--) {
    const xs = [];
    for (let x = 0; x < width; x++) if (alpha(x, y) > 128) xs.push(x);
    if (xs.length) return Math.round((xs[0] + xs[xs.length - 1]) / 2);
  }
  return Math.round(width / 2);
}

const source = readFileSync("lib/home-data.ts", "utf8");
// Plain names ("sofa_SE") and helper templates (`sofa_${dir}`) both count.
const bases = [...new Set([...source.matchAll(/["`]([a-zA-Z0-9]+)_(?:NE|NW|SE|SW|\$\{dir\})["`]/g)].map((m) => m[1]))].sort();
const names = bases.flatMap((b) => DIRS.map((d) => `${b}_${d}`)).sort();

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (f.endsWith(".png")) rmSync(`${OUT}/${f}`);

const rows = names.map((n) => {
  copyFileSync(`${KIT}/${n}.png`, `${OUT}/${n}.png`);
  const img = decodeAlpha(readFileSync(`${OUT}/${n}.png`));
  return `  ${n}: [${img.width}, ${img.height}, ${frontX(img)}],`;
});

writeFileSync(
  "lib/furniture-sizes.ts",
  `/**\n * Kenney furniture sprites in public/qn/furniture: [width, height, x of the front corner] in px.\n * Generated by scripts/sync-furniture.mjs.\n */\nexport const SPRITE_SIZE = {\n${rows.join("\n")}\n} as const;\n`,
);
console.log(`${names.length} sprites from ${bases.length} models`);
