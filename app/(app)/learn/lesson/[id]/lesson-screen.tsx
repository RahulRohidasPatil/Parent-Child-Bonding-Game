"use client";

import { useEffect, useId, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { BookMarked, ExternalLink, Layers, ListChecks, MessageCircleQuestion, Minus, Plus, Send, Swords } from "lucide-react";
import { Page } from "@/components/qn/app-shell";
import { LearnSteps } from "@/components/qn/learn-bits";
import { VisualFrame } from "@/components/qn/visual-frame";
import { Card, Notice, PageHeader, Spinner, Working } from "@/components/qn/ui";
import { Button, buttonVariants } from "@/components/ui/button";
import { ApiError, type PublicLesson, type PublicVisual, learnApi } from "@/lib/learn-api";
import { getState, remember } from "@/lib/store";
import { cn } from "@/lib/utils";

const COUNT_MIN = 3; // flashcards need at least 3
const COUNT_MAX = 15; // quizzes allow at most 15
const COUNT_DEFAULT = 5;
const TOPIC_MAX = 200; // the lesson API's topic limit

type FollowUp = { q: string; id?: string; lesson?: PublicLesson; drawing?: boolean; error?: string };

// Planned diagrams are drawn once per lesson. Guard against double calls (e.g. React's dev double effects).
const drawingNow = new Set<string>();

function readStore<T>(key: string, fallback: T): T {
  try {
    const raw = sessionStorage.getItem(key);
    return raw ? (JSON.parse(raw) as T) : fallback;
  } catch {
    return fallback;
  }
}
function writeStore(key: string, value: unknown) {
  try {
    sessionStorage.setItem(key, JSON.stringify(value));
  } catch {
    /* fine: only affects restoring after a reload */
  }
}

/** Draw a lesson's planned diagrams if it has any and none are drawn yet. Returns the new visuals. */
async function drawPlannedOnce(l: PublicLesson): Promise<PublicVisual[] | null> {
  const planned = l.sections.some((s) => s.visual);
  if (!planned || l.visuals.length > 0 || readStore(`qn.drawn.${l.id}`, false) || drawingNow.has(l.id)) return null;
  drawingNow.add(l.id);
  try {
    const { visuals } = await learnApi.drawVisuals(l.id);
    writeStore(`qn.drawn.${l.id}`, true);
    return visuals;
  } finally {
    drawingNow.delete(l.id);
  }
}

export function LessonScreen({ id }: { id: string }) {
  const router = useRouter();
  const askId = useId();
  const countId = useId();
  const [lesson, setLesson] = useState<PublicLesson | null>(null);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [drawing, setDrawing] = useState(false);
  const [followUps, setFollowUps] = useState<FollowUp[]>([]);
  const [ask, setAsk] = useState("");
  const [asking, setAsking] = useState(false);
  const [count, setCount] = useState(COUNT_DEFAULT);
  const [busy, setBusy] = useState<null | "quiz" | "deck">(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let live = true;
    learnApi
      .getLesson(id)
      .then(async (l) => {
        if (!live) return;
        setLesson(l);
        const prev = getState().recent.find((r) => r.kind === "lesson" && r.id === id);
        remember({ kind: "lesson", id, title: l.title, subject: prev?.subject, detail: prev?.detail ?? l.summary });

        // Restore follow-up answers asked earlier in this session.
        const saved = readStore<{ q: string; id: string }[]>(`qn.followups.${id}`, []);
        if (saved.length) {
          setFollowUps(saved.map((f) => ({ q: f.q, id: f.id })));
          saved.forEach((f) =>
            learnApi
              .getLesson(f.id)
              .then((a) => live && setFollowUps((list) => list.map((x) => (x.id === f.id ? { ...x, lesson: a } : x))))
              .catch(() => live && setFollowUps((list) => list.map((x) => (x.id === f.id ? { ...x, error: "This answer is no longer available." } : x)))),
          );
        }

        // Pictures are generated by default.
        if (l.sections.some((s) => s.visual) && l.visuals.length === 0 && !readStore(`qn.drawn.${l.id}`, false)) {
          setDrawing(true);
          try {
            const visuals = await drawPlannedOnce(l);
            if (live && visuals) setLesson((cur) => (cur ? { ...cur, visuals: [...cur.visuals, ...visuals] } : cur));
          } catch (e) {
            if (live) setError(e instanceof ApiError ? e.message : "Couldn’t draw the diagrams.");
          } finally {
            if (live) setDrawing(false);
          }
        }
      })
      .catch((e) => live && setLoadError(e instanceof ApiError ? e.message : "Couldn’t load the lesson."));
    return () => {
      live = false;
    };
  }, [id]);

  async function askFollowUp() {
    if (!lesson) return;
    const q = ask.trim();
    if (!q) return;
    setAsking(true);
    setError(null);
    // A follow-up is answered as a short lesson on the question, at the same age and from the same pages.
    const topic = lesson.source ? q : `${q} (about ${lesson.title})`;
    const entry: FollowUp = { q };
    setFollowUps((list) => [...list, entry]);
    setAsk("");
    try {
      const answer = await learnApi.createLesson({
        topic: topic.slice(0, TOPIC_MAX),
        age: lesson.age,
        material_id: lesson.source?.material_id ?? null,
      });
      setFollowUps((list) => list.map((x) => (x === entry ? { ...x, id: answer.id, lesson: answer, drawing: answer.sections.some((s) => s.visual) } : x)));
      writeStore(`qn.followups.${lesson.id}`, [...readStore<{ q: string; id: string }[]>(`qn.followups.${lesson.id}`, []), { q, id: answer.id }]);
      remember({ kind: "lesson", id: answer.id, title: answer.title, detail: `Follow-up to ${lesson.title}` });
      try {
        const visuals = await drawPlannedOnce(answer);
        if (visuals) setFollowUps((list) => list.map((x) => (x.id === answer.id && x.lesson ? { ...x, lesson: { ...x.lesson, visuals: [...x.lesson.visuals, ...visuals] } } : x)));
      } finally {
        setFollowUps((list) => list.map((x) => (x.id === answer.id ? { ...x, drawing: false } : x)));
      }
    } catch (e) {
      const msg = e instanceof ApiError ? e.message : "Couldn’t answer that. Try again.";
      setFollowUps((list) => list.map((x) => (x === entry ? { ...x, error: msg } : x)));
    } finally {
      setAsking(false);
    }
  }

  async function start(kind: "quiz" | "deck") {
    if (!lesson) return;
    setBusy(kind);
    setError(null);
    const subject = getState().recent.find((r) => r.id === lesson.id)?.subject;
    try {
      if (kind === "quiz") {
        const q = await learnApi.createQuiz(lesson.id, count);
        remember({ kind: "quiz", id: q.id, title: q.title || lesson.title, lessonId: lesson.id, subject, detail: `${q.questions.length} questions` });
        router.push(`/play/solo/quiz/${q.id}`);
      } else {
        const d = await learnApi.createDeck(lesson.id, count);
        remember({ kind: "deck", id: d.id, title: d.title || lesson.title, lessonId: lesson.id, subject, detail: `${d.cards.length} cards` });
        router.push(`/play/solo/flashcards/${d.id}`);
      }
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Something went wrong. Try again.");
      setBusy(null);
    }
  }

  if (loadError)
    return (
      <Page className="max-w-[720px]">
        <PageHeader title="Lesson" back={{ href: "/learn", label: "Back to Learn" }} />
        <Notice>{loadError}</Notice>
        <Link href="/learn/new" className={cn(buttonVariants({ variant: "brand", size: "cta" }))}>
          Start a new lesson
        </Link>
      </Page>
    );

  if (!lesson)
    return (
      <Page className="max-w-[720px]">
        <div className="flex items-center gap-2.5 p-8 font-extrabold text-muted-foreground" role="status">
          <Spinner className="text-brand" /> Loading the lesson…
        </div>
      </Page>
    );

  if (busy)
    return (
      <Page className="max-w-[720px]">
        <Working
          title={busy === "quiz" ? `Making your ${count}-question quiz…` : `Making ${count} flashcards…`}
          steps={busy === "quiz" ? ["Picking the key ideas", "Writing questions", "Checking the answers"] : ["Picking terms", "Writing cards", "Adding diagrams"]}
        />
      </Page>
    );

  return (
    <Page className="max-w-[880px]">
      <LearnSteps step={3} />
      <PageHeader
        title={lesson.title}
        sub={lesson.source ? `From ${lesson.source.title} · ${lesson.source.label}` : `Written for age ${lesson.age}`}
        back={{ href: "/learn", label: "Back to Learn" }}
      />

      <article className="flex min-w-0 flex-col gap-4">
        <LessonBody lesson={lesson} drawing={drawing} />
      </article>

      {/* ---------- follow-up questions ---------- */}
      <section aria-labelledby={`${askId}-h`} className="flex flex-col gap-3">
        {followUps.map((f, i) => (
          <Card key={`${f.id ?? "pending"}-${i}`} className="flex flex-col gap-3 p-4 md:p-5">
            <span className="self-end rounded-[18px_18px_4px_18px] bg-night px-3.5 py-2.5 text-[15px] leading-snug font-extrabold text-white">{f.q}</span>
            {f.error ? (
              <Notice>{f.error}</Notice>
            ) : !f.lesson ? (
              <span className="flex items-center gap-2.5 text-[15px] font-extrabold text-muted-foreground" role="status">
                <Spinner className="text-brand" /> Writing the answer… this usually takes 10–40 seconds
              </span>
            ) : (
              <div className="flex flex-col gap-3">
                <p className="text-[16px] leading-relaxed font-bold text-[#1d4d3b]">{f.lesson.summary}</p>
                {f.lesson.sections.map((s, j) => (
                  <div key={j} className="flex flex-col gap-2">
                    <h3 className="text-[17px] font-black">{s.heading}</h3>
                    {paragraphs(s.body).map((p, k) => (
                      <p key={k} className="text-[16px] leading-relaxed font-semibold text-[#2b3a47]">
                        {p}
                      </p>
                    ))}
                    {f.lesson!.visuals
                      .filter((v) => v.section_index === j)
                      .map((v) => (
                        <Figure key={v.id} v={v} />
                      ))}
                    {s.visual && f.drawing && f.lesson!.visuals.every((v) => v.section_index !== j) && <DrawingNote kind={s.visual.kind} purpose={s.visual.purpose} />}
                  </div>
                ))}
                <Link href={`/learn/lesson/${f.lesson.id}`} className="flex items-center gap-1.5 self-start text-sm font-black text-brand-ink">
                  <ExternalLink className="size-4" /> Open as its own lesson
                </Link>
              </div>
            )}
          </Card>
        ))}

        <Card className="flex flex-col gap-3 p-4 md:p-5">
          <h2 id={`${askId}-h`} className="flex items-center gap-2 text-[19px] font-black">
            <MessageCircleQuestion className="size-5 text-brand" /> Ask a follow-up question
          </h2>
          <form
            className="flex flex-col gap-2.5 sm:flex-row"
            onSubmit={(e) => {
              e.preventDefault();
              askFollowUp();
            }}
          >
            <label htmlFor={askId} className="sr-only">
              Your follow-up question
            </label>
            <input
              id={askId}
              maxLength={TOPIC_MAX - 40}
              value={ask}
              onChange={(e) => setAsk(e.target.value)}
              placeholder="e.g. Why are leaves green?"
              className="h-[52px] w-full min-w-0 shrink-0 rounded-2xl border-[1.5px] sm:flex-1 sm:shrink border-input bg-field px-3.5 text-base font-bold text-foreground outline-none placeholder:font-semibold placeholder:text-[#7b8994] focus-visible:border-brand"
            />
            <Button type="submit" variant="brand" size="pill" className="h-[52px]" disabled={asking || !ask.trim()}>
              {asking ? <Spinner /> : <Send />} Ask
            </Button>
          </form>
          <span className="text-[13px] font-bold text-muted-foreground">
            {lesson.source ? "Answers use only what your pages say." : `Answers are written for age ${lesson.age}, with diagrams.`}
          </span>
        </Card>
      </section>

      {/* ---------- practise ---------- */}
      <Card className="flex flex-col gap-4 p-4 md:p-5">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <span className="text-[19px] font-black">Practise it</span>
          <div className="flex items-center gap-2.5">
            <label htmlFor={countId} className="text-[13px] font-extrabold text-muted-foreground">
              How many
            </label>
            <div className="flex items-center rounded-2xl border-[1.5px] border-input bg-field">
              <button
                type="button"
                aria-label="Fewer"
                onClick={() => setCount((c) => Math.max(COUNT_MIN, c - 1))}
                disabled={count <= COUNT_MIN}
                className="flex size-11 items-center justify-center rounded-l-2xl hover:bg-muted disabled:opacity-40"
              >
                <Minus className="size-[18px]" strokeWidth={2.6} />
              </button>
              <input
                id={countId}
                type="number"
                inputMode="numeric"
                min={COUNT_MIN}
                max={COUNT_MAX}
                value={count}
                onChange={(e) => {
                  const n = Math.round(Number(e.target.value));
                  if (Number.isFinite(n)) setCount(Math.max(COUNT_MIN, Math.min(COUNT_MAX, n)));
                }}
                className="h-11 w-12 bg-transparent text-center text-lg font-black outline-none [appearance:textfield] [&::-webkit-inner-spin-button]:appearance-none [&::-webkit-outer-spin-button]:appearance-none"
              />
              <button
                type="button"
                aria-label="More"
                onClick={() => setCount((c) => Math.min(COUNT_MAX, c + 1))}
                disabled={count >= COUNT_MAX}
                className="flex size-11 items-center justify-center rounded-r-2xl hover:bg-muted disabled:opacity-40"
              >
                <Plus className="size-[18px]" strokeWidth={2.6} />
              </button>
            </div>
          </div>
        </div>
        <div className="grid grid-cols-1 gap-2.5 sm:grid-cols-2">
          <Button variant="soft" size="cta" onClick={() => start("deck")}>
            <Layers /> Flashcards
          </Button>
          <Button variant="brand" size="cta" onClick={() => start("quiz")}>
            <ListChecks /> Create quiz
          </Button>
        </div>
        <span className="text-[13px] font-bold text-muted-foreground">
          Both open in Play · Solo. Pick {COUNT_MIN} to {COUNT_MAX}.
        </span>
      </Card>

      {error && <Notice onClose={() => setError(null)}>{error}</Notice>}

      <Link href={`/play/duel?lesson=${lesson.id}`} className="flex items-center justify-center gap-2 text-sm font-black text-brand-ink">
        <Swords className="size-4" /> Or challenge your family to a duel
      </Link>
    </Page>
  );
}

function paragraphs(body: string) {
  return body.split(/\n{2,}/).filter(Boolean);
}

function LessonBody({ lesson, drawing }: { lesson: PublicLesson; drawing: boolean }) {
  const visualsFor = (i: number) => lesson.visuals.filter((v) => v.section_index === i);
  const unplaced = lesson.visuals.filter((v) => v.section_index < 0 || v.section_index >= lesson.sections.length);
  return (
    <>
      <Card className="bg-brand-soft p-4 md:p-5">
        <p className="text-[16px] leading-relaxed font-bold text-[#1d4d3b] md:text-[17px]">{lesson.summary}</p>
      </Card>

      {lesson.sections.map((s, i) => (
        <Card key={i} className="flex flex-col gap-3 p-4 md:p-5">
          <h2 className="text-[19px] font-black md:text-[21px]">{s.heading}</h2>
          {paragraphs(s.body).map((para, j) => (
            <p key={j} className="text-[16px] leading-relaxed font-semibold text-[#2b3a47]">
              {para}
            </p>
          ))}
          {visualsFor(i).map((v) => (
            <Figure key={v.id} v={v} />
          ))}
          {s.visual && visualsFor(i).length === 0 && drawing && <DrawingNote kind={s.visual.kind} purpose={s.visual.purpose} />}
        </Card>
      ))}
      {unplaced.map((v) => (
        <Figure key={v.id} v={v} />
      ))}

      <Card className="flex flex-col gap-3 p-4 md:p-5">
        <h2 className="flex items-center gap-2 text-[19px] font-black">
          <BookMarked className="size-5 text-brand" /> Key points
        </h2>
        <ul className="flex flex-col gap-2">
          {lesson.key_points.map((p, i) => (
            <li key={i} className="flex gap-2.5 text-[16px] leading-snug font-bold">
              <span className="mt-[7px] size-2 shrink-0 rounded-full bg-brand" aria-hidden="true" />
              {p}
            </li>
          ))}
        </ul>
      </Card>
    </>
  );
}

function DrawingNote({ kind, purpose }: { kind: string; purpose: string }) {
  return (
    <div className="flex items-center gap-2.5 rounded-2xl border border-dashed border-[#c9d3d9] px-3.5 py-3 text-sm font-bold text-muted-foreground" role="status">
      <Spinner className="text-brand" />
      Drawing a {kind}: {purpose}
    </div>
  );
}

function Figure({ v }: { v: PublicVisual }) {
  return (
    <figure className="flex flex-col gap-2">
      <VisualFrame html={v.html} title={v.alt || v.title} />
      <figcaption className="text-sm leading-snug font-bold text-muted-foreground">
        <strong className="text-foreground">{v.title}.</strong> {v.caption}
      </figcaption>
    </figure>
  );
}
